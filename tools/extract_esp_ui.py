#!/usr/bin/env python3
"""
Regenerate the web dashboard's shared assets from the firmware.

main.cpp ships its entire dashboard as a gzipped byte array (UI_GZ) in PROGMEM.
Two things in there are worth reusing verbatim so the cloud page is visually
identical to the device page rather than a lookalike:

  web/astro-ui.css   the <style> block (design system v2.0, ~460 classes)
  web/icons.js       LOGO_SVG + the IC icon map (136 hand-drawn icons)

Usage:
    python3 tools/extract_esp_ui.py firmware/esp32/main.cpp web/

Also writes the full decompressed UI to /tmp/esp_ui.html for reference.
"""

import gzip
import re
import sys
from pathlib import Path


def extract_blob(main_cpp: Path) -> bytes:
    src = main_cpp.read_text(encoding="utf-8", errors="replace")
    # NB: the file also has "extern const uint8_t UI_GZ[] PROGMEM;" near the top,
    # so match the DEFINITION (the one followed by "={") or we'd read the extern.
    m = re.search(r"const uint8_t UI_GZ\[\]\s*PROGMEM\s*=\s*\{", src)
    if not m:
        raise SystemExit("UI_GZ definition not found in main.cpp")
    end = src.index("};", m.end())
    hexes = re.findall(r"0x([0-9A-Fa-f]{2})", src[m.start():end])
    if not hexes:
        raise SystemExit("no bytes found in UI_GZ")
    return bytes(int(h, 16) for h in hexes)


def build_css(html: str) -> str:
    m = re.search(r"<style>(.*?)</style>", html, re.S)
    if not m:
        raise SystemExit("<style> block not found in the decompressed UI")
    return (
        "/* Astro Smart Attendance - design system extracted verbatim from the\n"
        "   ESP32 firmware UI blob (UI_GZ) so the cloud page matches the device page.\n"
        "   Generated by tools/extract_esp_ui.py - edit the firmware, not this file. */\n"
        + m.group(1)
    )


def build_icons(html: str) -> str:
    i = html.index("const LOGO_SVG=")
    logo = html[i:html.index("\n\n", i)].strip()

    start = html.index("const IC={};")
    end = html.index("})();", start) + len("})();")
    block = html[start:end]

    m = re.search(r"const ic=.*?;", html[end:])
    if not m:
        raise SystemExit("ic() helper not found")
    ic = m.group(0)

    return (
        "/* Astro Smart Attendance - icon set + logo extracted verbatim from the\n"
        "   ESP32 firmware UI blob (UI_GZ): the same 136 icons the device draws.\n"
        "   Generated by tools/extract_esp_ui.py - edit the firmware, not this file. */\n"
        f"{logo}\n\n{block}\n{ic}\n\nexport {{ ic, LOGO_SVG }};\n"
    )


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__)
        return 2

    main_cpp = Path(sys.argv[1])
    outdir = Path(sys.argv[2])

    raw = gzip.decompress(extract_blob(main_cpp))
    html = raw.decode("utf-8", errors="replace")
    Path("/tmp/esp_ui.html").write_text(html, encoding="utf-8")

    css = build_css(html)
    icons = build_icons(html)

    (outdir / "astro-ui.css").write_text(css, encoding="utf-8")
    (outdir / "icons.js").write_text(icons, encoding="utf-8")

    print(f"decompressed UI : {len(raw):,} bytes -> /tmp/esp_ui.html")
    print(f"stylesheet      : {len(css):,} bytes -> {outdir/'astro-ui.css'}")
    print(f"icons + logo    : {len(icons):,} bytes -> {outdir/'icons.js'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
