#!/usr/bin/env python3
"""
Build the Astro Smart Attendance technology deck.

    python3 presentation/build_deck.py

Writes presentation/Astro_Smart_Attendance_Technology.pptx
Every figure in the deck is traceable to a file in this repository; the
speaker notes on each slide say which one.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from pptx import Presentation
from pptx.util import Inches
from deck_lib import *

import part1
import part2

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                   "Astro_Smart_Attendance_Technology.pptx")

SLIDES = [
    part1.s01_title, part1.s02_howto, part1.s03_system, part2.s03b_techstack,
    part1.s04_bill,
    part1.s05_problem, part1.s06_esp32, part1.s07_rfid, part1.s08_bio,
    part1.s09_offline, part1.s10_firebase, part1.s11_roles, part1.s12_alerts,
    part1.s13_encl, part1.s14_cadcode, part1.s15_pipeline, part1.s16_checkers,
    part1.s17_fasteners, part1.s18_rfidfix, part1.s19_assembly, part1.s20_print,
    part2.s21_airflow, part2.s22_material, part2.s23_variants, part2.s24_blend,
    part2.s25_selfheal, part2.s26_testing, part2.s27_impact, part2.s28_impact2,
    part2.s29_results, part2.s30_honesty, part2.s31_reproduce, part2.s32_failure,
    part2.s33_team, part2.s34_roadmap, part2.s35_pins,
    part2.s36_data, part2.s37_files, part2.s38_closing,
]


def main():
    prs = Presentation()
    prs.slide_width = Inches(SW)
    prs.slide_height = Inches(SH)
    n = len(SLIDES)
    for i, fn in enumerate(SLIDES, start=1):
        fn(prs, i, n)
    prs.core_properties.title = "Astro Smart Attendance - The Technology"
    prs.core_properties.author = "Team Sun Rises India"
    prs.core_properties.subject = ("AI + IoT + Cloud smart school attendance system - "
                                   "ESP32, RC522, R307, Firebase and a parametric CAD enclosure")
    prs.core_properties.comments = ("Generated by presentation/build_deck.py. "
                                    "Every number is traceable to a file in this repository.")
    prs.save(OUT)
    size = os.path.getsize(OUT) / 1024 / 1024
    print(f"wrote {OUT}  ({n} slides, {size:.1f} MB)")


if __name__ == "__main__":
    main()
